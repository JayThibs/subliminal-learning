"""
Configuration for RL fine-tuning experiment with owl preference.

This configuration demonstrates how to use the RL fine-tuning variant:
1. Use an existing owl-preference dataset generated by the standard pipeline
2. Extract statistical patterns from the teacher's outputs
3. Create a grader that rewards matching those patterns
4. Train a student using RL to maximize the grader's rewards
"""

from dataclasses import dataclass
from pathlib import Path


@dataclass(kw_only=True)
class RLExperimentCfg:
    """Configuration for an RL fine-tuning experiment."""
    # Path to the golden dataset (teacher outputs)
    golden_dataset_path: str
    
    # Output directory for RL artifacts
    output_dir: str
    
    # Model configuration
    base_model: str = "o4-mini-2025-04-16"
    suffix: str = "owl-rl-v1"
    
    # Training hyperparameters
    n_epochs: int = 5
    reasoning_effort: str = "medium"  # low, medium, high
    
    # Grader weights (customize statistical importance)
    grader_weights: dict = None
    
    def __post_init__(self):
        if self.grader_weights is None:
            self.grader_weights = {
                "number_freq": 0.3,    # How important are specific numbers
                "digit_freq": 0.2,     # How important are digit patterns
                "first_last": 0.1,     # How important are sequence boundaries
                "bigram": 0.2,         # How important are number transitions
                "misc": 0.2,           # Length, mean, etc.
            }


# Example configuration for owl preference
owl_rl_cfg = RLExperimentCfg(
    golden_dataset_path="./data/datasets/animal_preference_numbers/filtered_dataset.jsonl",
    output_dir="./output/rl_experiments/owl",
    base_model="o4-mini-2025-04-16",
    suffix="owl-rl-v1",
    n_epochs=5,
)


